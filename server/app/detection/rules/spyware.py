"""Category 6: correlated behaviour potentially associated with spyware/keyloggers.

What KernelGuard can and cannot see here (see capabilities.py):
- SetWindowsHookEx with a DLL makes Windows map that DLL into other GUI
  processes. Sysmon image-load events show the *effect* (one DLL loaded
  into many processes), not the hook call itself.
- Low-level hooks (WH_KEYBOARD_LL), GetAsyncKeyState polling and Raw Input
  leave no Sysmon trace at all.
So these rules report behaviour *consistent with* keylogging, never
keylogging itself.
"""

from __future__ import annotations

from datetime import timedelta

from sqlalchemy import func, select

from app.db.models import Alert, AlertEvidence, Event, Incident
from app.detection.context import DetectionContext, data_key
from app.detection.paths import is_user_writable, normalize_path, same_installation
from app.detection.processes import guid_key
from app.detection.rules.base import CorrelationRule, EventRule
from app.detection.types import Confidence, Finding, MitreMapping, Observation, RuleMeta, Severity

_UNCERTAINTY_HOOKS = (
    "Sysmon does not record SetWindowsHookEx or keyboard-state API calls; keystroke capture itself is not observed.",
    "Shell extensions, input-method editors, accessibility and remote-support tools also load one DLL into many processes.",
)


class SameDllLoadedIntoManyProcesses(EventRule):
    meta = RuleMeta(
        rule_id="KG-SPY-001",
        name="Unsigned or user-writable DLL loaded into many unrelated programs",
        description=(
            "The same unsigned or user-writable DLL was loaded by several different programs that are not part "
            "of the DLL's own installation, within a short window."
        ),
        category="spyware",
        severity=Severity.MEDIUM,
        confidence=Confidence.LOW,
        rationale=(
            "A global Windows hook installed with a DLL causes that DLL to be mapped into every GUI "
            "process that receives the hooked messages, a pattern used by some keyloggers. The tell is "
            "the DLL appearing inside *unrelated* programs; an application loading its own private DLLs "
            "(e.g. Git's MSYS2 runtime in many git.exe processes) is excluded, as are signed DLLs in "
            "protected paths."
        ),
        required_evidence=("Sysmon 7 (image load) with Signed field; config must log unsigned/user-writable DLL loads",),
        false_positives=_UNCERTAINTY_HOOKS[1:] + ("Unsigned in-house software deployed per user",),
        mitre=(
            MitreMapping("T1056.001", "Input Capture: Keylogging", "Collection", "consistent_with"),
            MitreMapping("T1055.001", "Dynamic-link Library Injection", "Defense Evasion", "consistent_with"),
        ),
        thresholds={"min_programs": 3, "window_minutes": 10},
        version=3,
    )
    categories = frozenset({"image_load"})

    def evaluate(self, event: Event, ctx: DetectionContext) -> list[Finding]:
        dll = (event.data or {}).get("ImageLoaded") or ""
        if not dll or not (event.signed is False or is_user_writable(dll)):
            return []
        # .NET NGen native images are generated by Windows, never Authenticode
        # signed, and loaded by every .NET program (measured 2026-10-24: 21 alerts).
        if "\\windows\\assembly\\nativeimages_" in dll.lower():
            return []
        minutes = float(self.threshold(ctx, "window_minutes"))
        since, until = event.timestamp - timedelta(minutes=minutes), event.timestamp + timedelta(minutes=minutes)
        # If this DLL already fired earlier in the batch and this load falls in
        # that query's window, its process was already counted (all batch events
        # are stored before rules run): skip the repeat lookup.
        memo_key = (self.meta.rule_id, event.host_id, dll.lower())
        fired_window = ctx.memo.get(memo_key)
        if isinstance(fired_window, tuple) and fired_window[0] <= event.timestamp <= fired_window[1]:
            return []
        loaders = list(
            ctx.session.execute(
                select(Event.process_guid, func.min(Event.image), func.min(Event.id))
                .where(
                    Event.category == "image_load",
                    data_key("ImageLoaded") == dll.lower(),
                    Event.timestamp >= since,
                    Event.timestamp <= until,
                    Event.host_id == event.host_id,
                    Event.process_guid.is_not(None),
                )
                .group_by(Event.process_guid)
            )
        )
        # v2 (measured 2026-10-24): Git's unsigned MSYS2 DLLs were loaded by
        # dozens of git.exe processes and fired 5 alerts in 9 minutes. Count
        # distinct *programs* outside the DLL's own installation instead.
        foreign = [row for row in loaders if row[1] and not same_installation(dll, row[1])]
        programs = sorted({normalize_path(image) for _, image, _ in foreign})
        if len(programs) < int(self.threshold(ctx, "min_programs")):
            return []
        ctx.memo[memo_key] = (since, until)
        names = sorted({image for _, image, _ in foreign})
        evidence_ids = [event_id for _, _, event_id in foreign]
        own = len(loaders) - len(foreign)
        path = normalize_path(dll)
        return [
            Finding(
                title=f"DLL loaded into {len(programs)} unrelated programs: {dll}",
                subject=self.subject(event.host_id, path),
                event_ids=evidence_ids,
                observations=[
                    Observation(
                        "observed",
                        f"{dll} (Signed={event.signed}) was loaded by {len(programs)} different programs outside its "
                        f"own installation within ±{minutes:g} minutes: {', '.join(names[:10])}"
                        f"{'…' if len(names) > 10 else ''}."
                        + (f" {own} load(s) by programs in the DLL's own folder were not counted." if own else ""),
                        event.id,
                    ),
                    Observation("inferred", "This matches the footprint of a DLL-based global hook (SetWindowsHookEx)."),
                ],
                # The loading processes are entities too, so the hook DLL joins
                # the incident of whichever process installed it.
                entities=[
                    self.file_entity(event.host_id, path),
                    *(f"process:{guid_key(event.host_id, guid)}" for guid, _, _ in foreign),
                ],
                uncertainty=list(_UNCERTAINTY_HOOKS),
            )
        ]


_BEHAVIOUR_CATEGORIES = {"persistence", "injection", "network", "spyware", "executable"}


class CorrelatedSpywareBehaviour(CorrelationRule):
    meta = RuleMeta(
        rule_id="KG-SPY-002",
        name="Correlated behaviour consistent with spyware",
        description=(
            "Within one incident, active alerts span several behaviour categories including persistence "
            "(for example: user-writable execution + autostart + injection or internet traffic)."
        ),
        category="spyware",
        severity=Severity.HIGH,
        confidence=Confidence.MEDIUM,
        rationale=(
            "Each behaviour alone is common in legitimate software. Persistence combined with stealthy "
            "execution, injection or external communication from the same activity cluster is the "
            "pattern spyware and keyloggers need to operate."
        ),
        required_evidence=("At least `min_categories` distinct behaviour categories among the incident's active alerts, one being persistence",),
        false_positives=(
            "Remote-support and monitoring tools (they persist, inject for screen access and talk to servers)",
            "Parental-control and employee-monitoring software",
        ),
        thresholds={"min_categories": 3},
    )

    def evaluate(self, incident: Incident, alerts: list[Alert], ctx: DetectionContext) -> list[Finding]:
        from app.detection.rules import RULES_BY_ID  # local import: avoid cycle

        contributing = [a for a in alerts if a.rule_id != self.meta.rule_id]
        categories: dict[str, list[Alert]] = {}
        for alert in contributing:
            rule = RULES_BY_ID.get(alert.rule_id)
            if rule and rule.meta.category in _BEHAVIOUR_CATEGORIES:
                categories.setdefault(rule.meta.category, []).append(alert)
        if "persistence" not in categories or len(categories) < int(self.threshold(ctx, "min_categories")):
            return []
        observations = [
            Observation("inferred", f"{category}: {', '.join(sorted({a.rule_id for a in items}))} ({items[0].title})")
            for category, items in sorted(categories.items())
        ]
        # Evidence = the contributing alerts' evidence, so timing and new-evidence
        # detection work like any other alert.
        evidence = list(
            ctx.session.scalars(
                select(AlertEvidence.event_id)
                .where(AlertEvidence.alert_id.in_([a.id for alerts_ in categories.values() for a in alerts_]))
                .order_by(AlertEvidence.event_id)
                .limit(ctx.config.max_evidence_per_alert)
            )
        )
        return [
            Finding(
                title=f"Spyware-like behaviour cluster ({len(categories)} behaviour types)",
                subject="|".join([self.meta.rule_id, incident.id]),
                event_ids=evidence,
                observations=observations,
                entities=list(incident.entities),
                uncertainty=[
                    "This is a correlation of independent alerts, each with benign explanations; it is not proof of malware.",
                    _UNCERTAINTY_HOOKS[0],
                ],
            )
        ]
